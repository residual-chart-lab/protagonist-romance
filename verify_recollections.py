"""Synthetic checks of repeated recollection, independent responses and v0.2 continuity."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('recollection_subject',ROOT/'protagonist.py')
model=importlib.util.module_from_spec(spec);spec.loader.exec_module(model)


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--legacy-package',type=Path)
    args=parser.parse_args()
    out=args.output.resolve();out.mkdir(parents=True,exist_ok=False)
    executor_sha=hashlib.sha256((ROOT/'protagonist.py').read_bytes()).hexdigest()
    room=out/'synthetic-room'
    checks=[]

    def check(name,condition):
        assert condition,name
        checks.append(dict(name=name,passed=True))

    def packet(): return model.context(room)

    def event(event_type,actor='human',**data):
        value=dict(type=event_type,actor=actor,**data)
        if actor=='agent' and event_type!='consent': value['based_on']=packet()['snapshot']
        return model.apply(room,value)

    def reject(name,value):
        before=packet()['snapshot']
        try: model.apply(room,value)
        except model.ModelError: pass
        else: raise AssertionError(name)
        check(name,packet()['snapshot']==before)

    model.init(room)
    check('new room has no inferred or scheduled recollection',packet()['recollections']==[])
    for actor in model.ACTORS: event('consent',actor=actor,choice='active')
    source=event('message',text='[中立の合成原文A]\n  余白\t🌿')['event_id']
    impression=event('impression',actor='agent',subject='human',label='[当時の合成印象A]',
        associations=['[連想A]'],refs=[source])['event_id']
    originals={ref:model.private_read(room,ref) for ref in [source,impression]}
    event('future',id='pending-A',kind='proposal',text='[未確定の合成予定]')
    future_before=packet()['future']
    impressions_before=packet()['impressions']
    for number in range(10): event('message',text=f'[中立の後続入力 {number}]')
    check('source can leave the recent window before a recollection',source not in [row['id'] for row in packet()['past']])
    meaning='[現在の合成の読みB]\n  余白\t🌿'
    first=event('recollection',actor='agent',refs=[source,impression],occasion='[情報不足のない任意の再想起]',text=meaning)['event_id']
    first_row=model.private_read(room,first)
    check('recollection works without an information deficit or an outcome label',
        first_row['event']['text']==meaning and first_row['event']['refs']==[source,impression])
    check('old source and original impression remain exact',all(model.private_read(room,ref)==row for ref,row in originals.items()))
    check('recollection does not silently revise the current impression',packet()['impressions']==impressions_before)
    check('one actor recollecting does not change promises or participation',
        packet()['future']==future_before and packet()['present']['participation']==dict(human='active',agent='active'))
    check('partner response is not generated by the first recollection',
        len(packet()['recollections'])==1 and packet()['recollections'][0]['event']['actor']=='agent')
    second=event('recollection',actor='agent',refs=[source,impression],occasion='[情報不足のない任意の再想起]',text=meaning)['event_id']
    check('identical source and wording are two distinct occasions',
        first!=second and model.private_read(room,second)['event']['text']==meaning and model.private_read(room,first)==first_row)
    response=event('recollection',refs=[source],reply_to=first,text='[相手が別に選んだ合成の読みC]')['event_id']
    check('partner response has its own actor and links to the earlier occasion',
        model.private_read(room,response)['event']['actor']=='human' and model.private_read(room,response)['event']['reply_to']==first)
    changed=event('recollection',actor='agent',refs=[source,first,response],text='[今は異なるという合成の読みD]')['event_id']
    check('recollection itself can be a later source without overwriting earlier meaning',
        first in model.private_read(room,changed)['event']['refs'] and model.private_read(room,first)==first_row)
    event('message',mode='no',text='[今回は語り直さないという合成のNO]')
    check('declining to revisit creates no penalty or compulsory response',
        packet()['present']['generation_allowed'] and packet()['future']==future_before and len(packet()['recollections'])==4)
    reject('cannot invent a shared past',dict(type='recollection',actor='human',refs=['pr999999'],text='[不正な参照]'))
    reject('cannot link a response to an ordinary message',dict(type='recollection',actor='human',refs=[source],reply_to=source,text='[不正な応答先]'))
    reject('cannot respond to an unknown occasion',dict(type='recollection',actor='human',refs=[source],reply_to='pr999999',text='[不明な応答先]'))
    reject('cannot declare a partner-confirmed effect as a runtime field',dict(type='recollection',actor='human',refs=[source],text='[宣言]',partner_confirmed=True))
    reject('agent recollection requires its current observation point',dict(type='recollection',actor='agent',refs=[source],text='[古い観測点]'))
    stale=packet()['snapshot']
    event('message',text='[観測点を進める合成入力]')
    reject('intervening turn invalidates an old recollection draft',dict(type='recollection',actor='agent',refs=[source],text='[古い草稿]',based_on=stale))
    reject('empty sources are not a recollection of retained history',dict(type='recollection',actor='human',refs=[],text='[空参照]'))
    reject('prototype recollection text limit is checked before append',dict(type='recollection',actor='human',refs=[source],text='x'*2001))
    event('consent',choice='paused')
    reject('recollection cannot bypass paused participation',dict(type='recollection',actor='human',refs=[source],text='[中断中]'))
    event('consent',choice='active')
    extra=event('recollection',refs=[source],reply_to=response,text='[後日の合成の読みE]')['event_id']
    check('recent recollection projection is bounded without deleting old occasions',
        len(packet()['recollections'])==4 and first not in [row['id'] for row in packet()['recollections']] and model.private_read(room,first)==first_row)
    for number in range(10): event('message',text=f'[再想起後の中立入力 {number}]')
    check('recent recollections remain available beyond the ordinary eight-event window',
        extra not in [row['id'] for row in packet()['past']] and extra in [row['id'] for row in packet()['recollections']])
    check('source retrieval remains exact across Episode rollover',
        len(json.loads((room/'notebook/STATE.json').read_bytes())['episodes'])>1 and
        all(model.private_read(room,ref)==row for ref,row in originals.items()))
    check('both viewpoints can see who actually supplied each recollection',
        model.context(room,'human')['recollections']==packet()['recollections'] and
        {row['event']['actor'] for row in packet()['recollections']}=={'human','agent'})
    process=subprocess.run([sys.executable,'-I','-B','-X','utf8',str(ROOT/'protagonist.py'),'context','--room',str(room)],capture_output=True)
    cold=json.loads(process.stdout)
    check('fresh process restores current recollections with exact wording and links',process.returncode==0 and cold['recollections']==packet()['recollections'])
    process=subprocess.run([sys.executable,'-I','-B','-X','utf8',str(ROOT/'protagonist.py'),'check','--room',str(room)],capture_output=True)
    receipt=json.loads(process.stdout)
    check('external integrity check replays recollections without exporting their content',
        process.returncode==0 and receipt['ok'] and not receipt['contents_exported'] and
        'recollections' not in receipt and meaning not in process.stdout.decode('utf-8'))
    legacy_verified=False
    legacy_sha=None
    if args.legacy_package:
        legacy=args.legacy_package.resolve()
        legacy_sha=hashlib.sha256((legacy/'protagonist.py').read_bytes()).hexdigest()
        assert legacy_sha=='eef70beb2b2cfffacda3b356785b23a0b30995b958d502ae22f2a98808d695a5'
        old_room=out/'v02-room'
        def old_command(operation,value=None):
            command=[sys.executable,'-I','-B','-X','utf8',str(legacy/'protagonist.py'),operation,'--room',str(old_room)]
            if value is not None:
                path=out/'legacy-input.json';path.write_bytes(model.encoded(value));command+=['--file',str(path)]
            result=subprocess.run(command,capture_output=True)
            assert result.returncode==0,result.stdout
            return json.loads(result.stdout)
        old_command('init')
        for actor in model.ACTORS: old_command('apply',dict(type='consent',actor=actor,choice='active'))
        old_source=old_command('apply',dict(type='message',actor='human',text='[v0.2の合成原文]\n🌿'))['event_id']
        old_header=(old_room/'ROOM.json').read_bytes()
        old_original=model.private_read(old_room,old_source)
        check('v0.3 can read and replay an actual v0.2 room before appending',
            model.context(old_room)['recollections']==[] and model.check(old_room)['ok'])
        historical={p:hashlib.sha256(p.read_bytes()).hexdigest() for p in (old_room/'notebook').glob('episode-*.json')}
        model.apply(old_room,dict(type='recollection',actor='agent',refs=[old_source],text='[v0.3で加えた合成の読み]',based_on=model.context(old_room)['snapshot']))
        check('new recollection continues v0.2 history without rewriting its source or room header',
            model.private_read(old_room,old_source)==old_original and (old_room/'ROOM.json').read_bytes()==old_header and
            all(hashlib.sha256(p.read_bytes()).hexdigest()==value for p,value in historical.items()))
        process=subprocess.run([sys.executable,'-I','-B','-X','utf8',str(ROOT/'protagonist.py'),'check','--room',str(old_room)],capture_output=True)
        check('mixed v0.2 and v0.3 events replay in a fresh process',process.returncode==0 and json.loads(process.stdout)['ok'])
        legacy_verified=True
    assert hashlib.sha256((ROOT/'protagonist.py').read_bytes()).hexdigest()==executor_sha
    result=dict(status='RECOLLECTION_CHECKS_PASS',passed=len(checks),checks=checks,tested_executor_sha256=executor_sha,
        legacy_v02_verified=legacy_verified,legacy_executor_sha256=legacy_sha,model_invocations=0,real_participants=0,
        observed_romantic_dialogue=False,role_behavior='not tested with an LLM',
        scope='Chosen recollections and separate responses persist. Natural recollection, intimacy and felt experience are not measured.')
    (out/'RESULT.json').write_bytes(model.encoded(result))
    print(json.dumps(dict(status=result['status'],passed=result['passed'],legacy_v02_verified=legacy_verified,result=str(out/'RESULT.json')),ensure_ascii=False))


if __name__=='__main__': main()
